"""Business operations for book CRUD workflows."""

from sqlalchemy.exc import IntegrityError
from sqlmodel import Session, select

from fastapi import HTTPException, status

from app.models import (
    Author,
    Book,
    BookCreate,
    BookPublic,
    BookUpdate,
    StockAdjustment,
)


def _to_public(book: Book, author: Author) -> BookPublic:
    """Convert database models into the response shape exposed by the API."""
    # author_name comes from the related author, not from the books table.
    return BookPublic(
        id=book.id,
        title=book.title,
        isbn=book.isbn,
        price=book.price,
        stock=book.stock,
        author_id=book.author_id,
        author_name=author.name,
        created_at=book.created_at,
        updated_at=book.updated_at,
    )


def _get_book_or_404(session: Session, book_id: int) -> Book:
    """Fetch a book or raise a not-found HTTP error."""
    book = session.get(Book, book_id)

    if book is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book not found",
        )

    return book


def _get_author_or_404(session: Session, author_id: int) -> Author:
    """Fetch an author or raise a not-found HTTP error."""
    author = session.get(Author, author_id)

    if author is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Author not found",
        )

    return author


def create_book(session: Session, book_data: BookCreate) -> BookPublic:
    """Create a book after validating its author and ISBN uniqueness."""
    # A foreign-key check here provides a clear API error before insertion.
    author = _get_author_or_404(session, book_data.author_id)
    isbn = book_data.isbn.strip()

    # This friendly check complements the database unique constraint.
    existing_book = session.exec(
        select(Book).where(Book.isbn == isbn)
    ).first()

    if existing_book:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="A book with this ISBN already exists",
        )

    # Timestamps are generated by PostgreSQL, so do not validate them from
    # the request schema when constructing the table model.
    book = Book(
        title=book_data.title,
        isbn=isbn,
        price=book_data.price,
        stock=book_data.stock,
        author_id=book_data.author_id,
    )

    try:
        # Commit persists the row; refresh loads its generated ID/timestamps.
        session.add(book)
        session.commit()
        session.refresh(book)
        return _to_public(book, author)
    except IntegrityError as exc:
        session.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Could not create book because of a database conflict",
        ) from exc
    except Exception:
        session.rollback()
        raise


def list_books(
    session: Session,
    *,
    offset: int = 0,
    limit: int = 20,
) -> list[BookPublic]:
    """Return books in stable ID order with pagination."""
    books = session.exec(
        select(Book)
        .order_by(Book.id)
        .offset(offset)
        .limit(limit)
    ).all()

    results: list[BookPublic] = []
    for book in books:
        # This simple lookup is clear for learning; a join can optimize it later.
        author = _get_author_or_404(session, book.author_id)
        results.append(_to_public(book, author))

    return results


def get_book(session: Session, book_id: int) -> BookPublic:
    """Return one book with its author's public name."""
    book = _get_book_or_404(session, book_id)
    author = _get_author_or_404(session, book.author_id)
    return _to_public(book, author)


def update_book(
    session: Session,
    book_id: int,
    book_data: BookUpdate,
) -> BookPublic:
    """Update editable fields while keeping stock outside general PATCH."""
    book = _get_book_or_404(session, book_id)
    update_data = book_data.model_dump(exclude_unset=True)

    # Explicit nulls are rejected for fields that must remain populated.
    for field in ("title", "isbn", "price", "author_id"):
        if field in update_data and update_data[field] is None:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"{field} cannot be null",
            )

    if "isbn" in update_data:
        update_data["isbn"] = update_data["isbn"].strip()
        duplicate = session.exec(
            select(Book).where(
                Book.isbn == update_data["isbn"],
                Book.id != book_id,
            )
        ).first()

        if duplicate:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="A book with this ISBN already exists",
            )

    if "author_id" in update_data:
        _get_author_or_404(session, update_data["author_id"])

    # Apply only fields sent by the client; stock is not in BookUpdate.
    for field, value in update_data.items():
        setattr(book, field, value)

    try:
        session.add(book)
        session.commit()
        session.refresh(book)
        author = _get_author_or_404(session, book.author_id)
        return _to_public(book, author)
    except IntegrityError as exc:
        session.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Could not update book because of a database conflict",
        ) from exc
    except Exception:
        session.rollback()
        raise


def delete_book(session: Session, book_id: int) -> None:
    """Delete a book and roll back if the database rejects the operation."""
    book = _get_book_or_404(session, book_id)

    try:
        session.delete(book)
        session.commit()
    except IntegrityError as exc:
        session.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Cannot delete this book because related records exist",
        ) from exc
    except Exception:
        session.rollback()
        raise


def adjust_book_stock(
    session: Session,
    book_id: int,
    adjustment: StockAdjustment,
) -> BookPublic:
    """Increase or decrease stock while locking the selected database row."""
    # PostgreSQL keeps this row locked until commit or rollback, preventing
    # concurrent requests from making decisions using stale stock values.
    statement = (
        select(Book)
        .where(Book.id == book_id)
        .with_for_update()
    )
    book = session.exec(statement).first()

    if book is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book not found",
        )

    quantity = adjustment.quantity
    if adjustment.action == "increase":
        book.stock += quantity
    elif quantity <= book.stock:
        book.stock -= quantity
    else:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Insufficient stock for this operation",
        )

    try:
        session.add(book)
        session.commit()
        session.refresh(book)

        author = _get_author_or_404(session, book.author_id)
        return _to_public(book, author)
    except Exception:
        session.rollback()
        raise
